"""Pack the pinned exporter into `wheels/io_xplane2blender-<version>-py3-none-any.whl`.

    python3 scripts/build_wheel.py

Blender installs the wheels an extension declares into
`extensions/.local/lib/pythonX.Y/site-packages`, which is on `sys.path` for every
extension, so `import io_xplane2blender` in `__init__.py` finds this copy.  That
is the whole reason the exporter ships as a wheel instead of as a subpackage:
the package keeps its upstream top-level name, so the code goes in **as upstream
writes it** - no relative-import conversion, no attribute-walk fixes, and the
tree stays byte-identical to `vendor/XPlane2Blender` (a submodule, so the
upstream history lives where it belongs) apart from the one entry in `PATCHES`
below, which is a crash the pinned commit does not yet fix.

The wheel is a build artifact and is gitignored: regenerated by CI before every
`extension build`, and locally by running this script.  Consequences worth
knowing before editing:

- `xplane2blender/tests/` must stay IN: `xplane_types/xplane_file.py` and
  `xplane_utils/xplane_wiper_gradient.py` import `test_creation_helpers` at run
  time, so a wheel without it registers and then exports nothing.
- `VERSION` below is the distribution version, which is NOT the extension's.
  It tracks upstream's `bl_info` and only moves when the vendored commit does.
- The zip is written deterministically (sorted entries, fixed timestamps), so a
  rebuild from the same submodule commit produces a byte-identical wheel; the
  sha256 printed at the end is the artifact identity.
- Editing the exporter means rebuilding: a symlinked dev install no longer sees
  the tree.  For live iteration put `vendor/XPlane2Blender` on `sys.path`
  instead of reinstalling.
"""
import base64
import hashlib
import os
import re
import sys
import zipfile
from typing import NoReturn

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
UPSTREAM = os.path.join(REPO, "vendor", "XPlane2Blender")
SRC = os.path.join(UPSTREAM, "io_xplane2blender")
OUT_DIR = os.path.join(REPO, "wheels")

NAME = "io_xplane2blender"
BASE_VERSION = "4.5.0"          # what upstream bl_info declares
# Bump the .postN whenever the packed bytes change - a new submodule pin, or an
# edit to PATCHES.  Blender keys the extracted copy by the dist-info directory
# name, so an unchanged version means the new wheel is never unpacked over the
# old files and the user keeps running the previous build.
VERSION = BASE_VERSION + ".post2"
TAG = "py3-none-any"

# 1980-01-01: the earliest timestamp a zip may carry.  Fixed so the archive is
# reproducible; nothing reads it.
ZIP_DATE = (1980, 1, 1, 0, 0, 0)
FILE_MODE = 0o644

SKIP_DIRS = {"__pycache__"}
SKIP_SUFFIXES = (".pyc", ".pyo", ".orig", ".rej")

# The only edits made to upstream source, applied to the bytes that go into the
# wheel.  Exact snippets, not regexes: if upstream changes the line, the build
# stops and names it instead of shipping a wheel that is silently unpatched.
# Keep this list at one entry - anything that is not a user-visible crash belongs
# in the fork, not here.
PATCHES = [
    # upstream reads context.active_object without a guard, so an empty scene
    # (no active object, i.e. right after installing) throws on every redraw of
    # the Render panel. One `is not None`.
    ("xplane_ui.py",
     "            if context.active_object.xplane.isExportableRoot:\n"
     "                active_root = context.active_object",
     "            active = context.active_object\n"
     "            if active is not None and active.xplane.isExportableRoot:\n"
     "                active_root = active"),
]

METADATA = """Metadata-Version: 2.1
Name: {name}
Version: {version}
Summary: XPlane2Blender export half, bundled by the X-Plane OBJ8 Import and Export extension
Home-page: https://github.com/X-Plane/XPlane2Blender
License: GPL-2.0-or-later
License-File: LICENSE
Author: Ted Greene, Ben Supnik, Amy Parent, Maya F. Eroglu
X-Vendored-Commit: {commit}
"""

WHEEL = """Wheel-Version: 1.0
Generator: io_scene_xplane_obj scripts/build_wheel.py
Root-Is-Purelib: true
Tag: {tag}
"""


def die(msg) -> NoReturn:
    print("build_wheel: %s" % msg, file=sys.stderr)
    raise SystemExit(1)


def upstream_version():
    """The `bl_info["version"]` upstream ships, as a string."""
    path = os.path.join(SRC, "__init__.py")
    with open(path, encoding="utf-8") as fh:
        text = fh.read()
    match = re.search(r'"version"\s*:\s*\(([^)]*)\)', text)
    if match is None:
        die("%s has no bl_info version" % path)
    parts = match.group(1).split(",")
    return ".".join(part.strip() for part in parts)


def vendored_commit():
    """Commit the submodule is checked out at, or 'unknown' outside git."""
    head = os.path.join(UPSTREAM, ".git")
    if not os.path.exists(head):
        return "unknown"
    try:
        import subprocess
        out = subprocess.run(["git", "-C", UPSTREAM, "rev-parse", "HEAD"],
                             capture_output=True, text=True, check=True)
    except Exception:                                     # noqa: BLE001
        return "unknown"
    return out.stdout.strip() or "unknown"


def package_files():
    """Every file of the exporter, as zip paths relative to the wheel root."""
    found = []
    for base, dirs, names in os.walk(SRC):
        dirs[:] = sorted(d for d in dirs if d not in SKIP_DIRS)
        for name in sorted(names):
            if name.endswith(SKIP_SUFFIXES) or name == ".DS_Store":
                continue
            path = os.path.join(base, name)
            rel = os.path.relpath(path, SRC).replace(os.sep, "/")
            found.append(("io_xplane2blender/" + rel, path))
    for required in ("__init__.py", "tests/test_creation_helpers.py",
                     "xplane_types/xplane_file.py"):
        if not os.path.isfile(os.path.join(SRC, required)):
            die("the exporter tree is missing %s - is the submodule checked out?"
                % required)
    if not found:
        die("no file under %s" % SRC)
    return found


def record_line(arcname, data):
    digest = base64.urlsafe_b64encode(hashlib.sha256(data).digest())
    return "%s,sha256=%s,%d" % (arcname, digest.rstrip(b"=").decode("ascii"),
                                len(data))


def apply_patches(entries):
    """Rewrite the patched files in place; die when a snippet is not there."""
    for name, old, new in PATCHES:
        old_bytes, new_bytes = old.encode("utf-8"), new.encode("utf-8")
        target = "io_xplane2blender/" + name
        hits = 0
        for index, (arcname, data) in enumerate(entries):
            if arcname != target:
                continue
            found = data.count(old_bytes)
            if found != 1:
                die("%s: expected the patched snippet once, found %d - upstream "
                    "moved that line" % (name, found))
            entries[index] = (arcname, data.replace(old_bytes, new_bytes))
            hits += 1
        if not hits:
            die("%s is not in the wheel, so the patch list is stale" % name)
    return entries


def main():
    if not os.path.isdir(SRC):
        die("%s does not exist - run `git submodule update --init` first" % SRC)
    shipped = upstream_version()
    if shipped != BASE_VERSION:
        die("BASE_VERSION is %s but the vendored exporter says %s - the wheel "
            "version tracks upstream, so move it deliberately"
            % (BASE_VERSION, shipped))

    dist_info = "%s-%s.dist-info" % (NAME, VERSION)
    entries = [(arcname, open(path, "rb").read())
               for arcname, path in package_files()]
    apply_patches(entries)
    entries.append((dist_info + "/METADATA",
                    METADATA.format(name=NAME, version=VERSION,
                                    commit=vendored_commit()).encode("utf-8")))
    entries.append((dist_info + "/WHEEL", WHEEL.format(tag=TAG).encode("utf-8")))
    license_path = os.path.join(UPSTREAM, "LICENSE")
    if not os.path.isfile(license_path):
        die("no LICENSE beside the exporter - GPL redistribution needs it")
    with open(license_path, "rb") as fh:
        entries.append((dist_info + "/LICENSE", fh.read()))
    entries.sort(key=lambda item: item[0])

    names = [arcname for arcname, _ in entries]
    if len(set(names)) != len(names):
        die("duplicate paths in the wheel: %s"
            % sorted({n for n in names if names.count(n) > 1}))
    if any(n.startswith("..") or "/../" in n for n in names):
        die("a path escapes the wheel root")

    record = [record_line(arcname, data) for arcname, data in entries]
    record.append(dist_info + "/RECORD,,")               # own hash is left empty
    entries.append((dist_info + "/RECORD",
                    ("\n".join(record) + "\n").encode("utf-8")))

    os.makedirs(OUT_DIR, exist_ok=True)
    out = os.path.join(OUT_DIR, "%s-%s-%s.whl" % (NAME, VERSION, TAG))
    # `extension build` packs the whole wheels/ directory, not just the file
    # `wheels = [...]` names, so an older wheel left behind ships as dead weight
    # (post1 + post2 was 656 KB of a 796 KB zip) and looks like two versions of
    # the exporter in one package.
    for stale in sorted(os.listdir(OUT_DIR)):
        if stale.startswith(NAME + "-") and stale.endswith(".whl") \
                and stale != os.path.basename(out):
            os.remove(os.path.join(OUT_DIR, stale))
            print("build_wheel: removed stale %s" % stale)
    tmp = out + ".tmp"
    with zipfile.ZipFile(tmp, "w", zipfile.ZIP_DEFLATED) as zf:
        for arcname, data in entries:
            info = zipfile.ZipInfo(arcname, date_time=ZIP_DATE)
            info.external_attr = (0o100000 | FILE_MODE) << 16
            info.compress_type = zipfile.ZIP_DEFLATED
            zf.writestr(info, data)
    os.replace(tmp, out)

    digest = hashlib.sha256(open(out, "rb").read()).hexdigest()
    print("build_wheel: %s (%d files, %.0f KB)" % (
        os.path.relpath(out, REPO), len(entries), os.path.getsize(out) / 1024.0))
    print("build_wheel: sha256 %s" % digest)
    print("build_wheel: declare it as wheels = [\"./wheels/%s\"] in "
          "blender_manifest.toml" % os.path.basename(out))


if __name__ == "__main__":
    main()
